import pandas as pd # Загрузка библиотек
import numpy as np
import os
import matplotlib.pyplot as plt
import seaborn as sns

def очистка_отчета(путь_к_файлу): # Функция для очистки отчета
    отчет = pd.read_excel(путь_к_файлу, skiprows=3) # Загрузка файла
    отчет = отчет.replace(' ', np.nan) # Заменяем одиночный пробел на Nan
    отчет = отчет.dropna(axis=1, how='all').dropna(how='all') # Удаляем полностью пустые столбцы и строки
    отчет['Номер'] = отчет['Номер'].str.replace(' ','', regex=False).str.lstrip('aаAА0').str.lower() # Заменяем пробелы на пустые строки, удаляем в столбце номер передние мусорные символы, 
    # приводим строку к нижнему регистру
    отчет = отчет.rename(columns={'Тип ТС':'Наименование транспортного средства'}) # Переименование столбца
    отчет['Дата заявки'] = pd.to_datetime(отчет['Дата заявки'], format='%d.%m.%Y',errors='coerce') # Приведение даты к datetime
    отчет = отчет.reset_index(drop=True) # Сбрасываем индекс и удаляем старый
    return отчет # Возвращаем отчет из функции

def очистка_реестра(путь_к_файлу, максимальная_длина_номера): # Функция для очистки реестра
    реестр = pd.read_excel(путь_к_файлу) # Загрузка файла
    реестр = реестр.dropna(axis=1, how='all').dropna(how='all') # Удаляем полностью пустые столбцы и строки
    реестр['Номер'] = реестр['Номер заявки/талона'].str.split('/', n=1).str[1] # Берём часть после первого слэша
    реестр['Номер'] = реестр['Номер'].fillna('').astype(str).replace(['nan', 'None'], '') # Преобразуем в строку и заменяем все пропуски на пустую строку
    реестр['Номер заявки/талона'] = реестр['Номер заявки/талона'].fillna('').replace(['nan', 'None'], '') # Заменяем мусорные значения на пустую строку
    реестр.loc[реестр['Номер'] == '', 'Номер'] = реестр['Номер заявки/талона'] # Присваиваем пустым строкам в столбце "Номер" обработанные значения из столбца Номер заявки/талона
    реестр['Номер'] = реестр['Номер'].str.replace(' ','',regex=False).str.lstrip('aаAА0').str.lower() # Заменяем пробелы на пустые строки, удаляем в столбце номер передние мусорные символы, 
    # приводим строку к нижнему регистру
    реестр['Дата начала по заявке (для спецтехники)'] = pd.to_datetime(реестр['Дата начала по заявке (для спецтехники)'],errors='coerce') # Приводим столбец к формату datetime
    реестр = реестр.reset_index(drop=True) # Сбрасываем индекс и удаляем старый
    не_цифры = ~ (реестр['Номер'].astype(str).str.isdigit()) # Ищем не цифры и сохраняем в переменную
    нестандартные_номера = реестр[(реестр['Номер'] != '') & не_цифры][['Номер']] # Не пробелы и не цифры сохраняем в переменную
    if not нестандартные_номера.empty:
        разделенные = нестандартные_номера['Номер'].str.split('\n', n=1, expand=True).reindex(columns=[0, 1]) # Разделяем по символу '\n' и сохраняем две части
        нестандартные_номера['Номер'] = np.where(разделенные[0].str.len() <= 2, разделенные[1], разделенные[0]) # В зависимости от длины строки берем второй или первый столбец переменной 'разделенные'
        нестандартные_номера['Номер'] = нестандартные_номера['Номер'].str.split('/', n=1, expand=True)[0] # Обрабатываем мусорные значения, чтобы извлечь больше данных, по разделителю, только первое вхождение,
        # берем первый столбец
        нестандартные_номера['Номер'] = нестандартные_номера['Номер'].str.strip('fв').str.lstrip('0') # убираем лишние символы и ведущие нули
        индексы_для_обновления = нестандартные_номера.index # Сохраняем индексы обработанных значений
        реестр.loc[индексы_для_обновления, 'Номер'] = нестандартные_номера['Номер'] # Присваеваем по индексам обработанные значения
    реестр['Номер'] = реестр['Номер'].str.split('от').str[0].str.split(';').str[0].str.split(':').str[0].str.split('(').str[0].fillna('').str.strip() 
    # Разделяем по нескольким разделителям берем первую строку, заменяем пустые значения на пустые строки и удаляем пробелы с двух сторон
    нестандартные_номера_еще = реестр[~(реестр['Номер'].str.isdigit()) & ~(реестр['Номер'] == '') & ~(реестр['Номер'] == ' ') & реестр['Номер'].notna()][['Номер']] 
    # Находим с помощью условий не цифры и не пустые строки и не пробелы и не пустые значения, выводим столбец и сохраняем в переменную
    нестандартные_номера_еще['Номер'] = нестандартные_номера_еще['Номер'].str[:максимальная_длина_номера] # Обрезаем номер до максимальная_длина_номера символов
    индексы_для_обновления_еще = нестандартные_номера_еще.index # Сохраняем индексы
    реестр.loc[индексы_для_обновления_еще, 'Номер'] = нестандартные_номера_еще['Номер'] # Обновляем значения в столбце 'Номер'
    реестр['Номер'] = реестр['Номер'].str.lstrip('0') # Удаляем ведущие нули в столбце
    реестр = реестр.rename(columns={'Дата начала по заявке (для спецтехники)':'Дата заявки'}) # Переименовываем столбец
    реестр = реестр.reset_index(drop=True) # Сбрасываем индекс в датафрейме и удаляем
    реестр['исходный_индекс'] = реестр.index # Сохраняем индекс
    return реестр # Возвращаем реестр из функции

def объединение(отчет, реестр, справочник_тс):
    отчет = pd.merge(отчет, справочник_тс, on='Наименование транспортного средства', how='left') # Объединение отчета и справочника
    реестр = pd.merge(реестр, справочник_тс, on='Наименование транспортного средства', how='left') # Объединение реестра и справочника
    реестр_отчет = pd.merge(реестр, отчет, on=['Номер', 'Дата заявки'], how='left',indicator=True, validate='m:1') # Объединение реестра и отчета
    реестр_отчет = реестр_отчет.rename(columns={'ТС_x':'ТС'}) # Переименовываем название колонки с суфиксом
    справочник_цехов = реестр_отчет[['Код цеха ', 'Подразделение']].drop_duplicates(subset=['Подразделение']) 
    # Создаем справочник из двух столбцов и удаляем дубликаты по столбцу 'Подразделение'
    справочник_цехов = справочник_цехов.sort_values(by=['Подразделение']) # Сортируем по подразделению
    отчет = pd.merge(отчет, справочник_цехов, on=['Подразделение'], how='left') # Объединяем отчет и справочник по подразделению
    не_объединены = реестр_отчет[реестр_отчет['_merge'] == 'left_only'] # Находим значению из левой таблицы не объединившиеся
    индексы_для_удаления = не_объединены['исходный_индекс'].tolist() # Преобразовываем сериес в список
    реестр_первая_часть = реестр_отчет.drop(индексы_для_удаления) # Создаем объединившуюся часть таблицы
    реестр_вторая_часть = реестр.loc[индексы_для_удаления] # Берем не объединившиеся значения из оригинального датафрейма
    отчет_без_дублей = отчет.drop_duplicates(subset=['Дата заявки', 'ТС', 'Код цеха ']) # Удаляем дубликаты по трем столбцам
    реестр_вторая_часть = pd.merge(реестр_вторая_часть, отчет_без_дублей, on=['Дата заявки', 'ТС', 'Код цеха '], how='left') # Используем другой способ объединения таблиц
    реестр_вторая_часть = реестр_вторая_часть.rename(columns={'Номер_x':'Номер'}) # Переименовываем название колонки с суфиксом
    реестр_вторая_часть['Источник'] = '2_часть' # Создаем две части для контроля объединения
    реестр_первая_часть['Источник'] = '1_часть'
    реестр_объединение = pd.concat([реестр_первая_часть, реестр_вторая_часть],ignore_index=True) # Объединяем с помощью конкат
    паттерны = ['_y','Наименование цеха_x','Номер_x','_merge']
    маска_для_удаления = np.where(реестр_объединение.columns.str.contains('|'.join(паттерны)), True, False)
    столбцы_для_удаления = реестр_объединение.columns[маска_для_удаления].tolist() # По маске выбираем колонки с суффиксом _y и служебную _merge
    реестр_объединение = реестр_объединение.drop(columns=столбцы_для_удаления) # Удаляем искомые столбцы
    реестр_объединение = реестр_объединение.rename(columns={
        '  ':'Месяц', # В исходном файле у колонки с месяцем заголовок из пробелов
        'Наименование транспортного средства_x': 'Наименование ТС',
        'Код цеха ': 'Код_цеха', # убираем пробел в конце
        'Фактическое время для оплаты согласно СКУД': 'Фактические_часы',
        'Наименование КА': 'Подрядчик',
        'Сумма итог руб. без НДС': 'Стоимость_руб'
    })
    реестр_объединение['Статус заявки'] = реестр_объединение['Статус заявки'].fillna('Не указан')
    реестр_объединение['Код_цеха'] = реестр_объединение['Код_цеха'].astype('Int64')
    реестр_объединение = реестр_объединение.drop(
    columns=['Номер заявки/талона', 'исходный_индекс', 'ТС', 'Подразделение']
    )
    return реестр_объединение

def очистка_госномеров(реестр_объединение):
    гн_нестандартные_номера = реестр_объединение[(
        реестр_объединение['Регистрационный номер автомобиля'].str.contains('RUS', na=False, case=False)) | (
        реестр_объединение['Регистрационный номер автомобиля'].str.contains('/', na=False, case=False)) | (
        реестр_объединение['Регистрационный номер автомобиля'].str.contains(' ', na=False, case=False))]['Регистрационный номер автомобиля']
    # Находим нестандартные_номера по трем условиям, сохраняем в переменную
    гн_нестандартные_номера = гн_нестандартные_номера.str.split('RUS').str[0].str.replace(' ','', regex=False).str.replace('/', '', regex=False) 
    # Сначала в нестандартных номерах находим строку 'RUS', берем значение до неё, заменяем пробелы и слэш на пустую строку
    индексы_гн_нестандартные_номера = гн_нестандартные_номера.index # Сохраняем индексы нестандартных номеров
    реестр_объединение.loc[индексы_гн_нестандартные_номера,['Регистрационный номер автомобиля']] = гн_нестандартные_номера # Присваиваем обработанные нестандартные_номера в столбец общей таблицы
    return реестр_объединение

def агрегация(реестр_объединение, цех_для_анализа):
    реестр_цеха = реестр_объединение[реестр_объединение['Код_цеха'] == цех_для_анализа].copy() # Фильтруем по цеху
    if реестр_цеха.empty:
        raise ValueError(f'В данных нет заявок по цеху {цех_для_анализа}')
    реестр_цеха['Маршрут'] = реестр_цеха['Адрес отправления'] + '-' + реестр_цеха['Адрес получения'] # Создаем столбец маршрут

    # По месяцам: сколько заявок, сколько часов и сколько в среднем часов на заявку
    порядок_месяцев = ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь',
                       'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь']
    по_месяцам = реестр_цеха.groupby('Месяц').agg(
        Заявок=('Фактические_часы', 'size'),
        Часы=('Фактические_часы', 'sum'),
        Среднее_часов_на_заявку=('Фактические_часы', 'mean')
    ).reindex(порядок_месяцев).round(1) # reindex ставит месяцы по порядку
    по_месяцам[['Заявок', 'Часы']] = по_месяцам[['Заявок', 'Часы']].fillna(0)

    # По маршрутам: сколько рейсов, сколько часов всего и сколько в среднем на один рейс
    по_маршрутам = реестр_цеха.groupby('Маршрут').agg(
        Рейсов=('Фактические_часы', 'size'),
        Часы=('Фактические_часы', 'sum'),
        Среднее_часов_на_рейс=('Фактические_часы', 'mean')
    ).sort_values('Часы', ascending=False).round(1)

    # По подрядчикам: объём, затраты и стоимость одного часа
    по_подрядчикам = реестр_цеха.groupby('Подрядчик').agg(
        Заявок=('Фактические_часы', 'size'),
        Часы=('Фактические_часы', 'sum'),
        Стоимость_руб=('Стоимость_руб', 'sum')
    )
    по_подрядчикам['Руб_за_час'] = (по_подрядчикам['Стоимость_руб'] / по_подрядчикам['Часы']).round(0)
    по_подрядчикам['Доля_часов_%'] = (100 * по_подрядчикам['Часы'] / по_подрядчикам['Часы'].sum()).round(1)
    по_подрядчикам['Доля_стоимости_%'] = (100 * по_подрядчикам['Стоимость_руб'] / по_подрядчикам['Стоимость_руб'].sum()).round(1)
    по_подрядчикам['Стоимость_тыс_руб'] = (по_подрядчикам['Стоимость_руб'] / 1000).round(1)
    по_подрядчикам = по_подрядчикам.drop(columns='Стоимость_руб').sort_values('Руб_за_час', ascending=False)
    # Группировка по типу груза
    по_грузам = реестр_цеха.groupby('Тип груза').agg(
        Рейсов=('Фактические_часы', 'size'),
        Часы=('Фактические_часы', 'sum'),
        Стоимость=('Стоимость_руб', 'sum')
    ).sort_values('Часы', ascending=False)
    по_грузам['Доля_часов_%'] = (100 * по_грузам['Часы'] / по_грузам['Часы'].sum()).round(1)

    return по_маршрутам, по_подрядчикам, по_месяцам, по_грузам

def визуализация(по_месяцам, по_маршрутам, по_подрядчикам, по_грузам, цех_для_анализа, папка_графиков, мин_рейсов=5):
    """Создаёт 4 графика по таблицам из функции агрегация() и сохраняет их в папку output/

    по_месяцам      - таблица: Заявок, Часы, Среднее_часов_на_заявку (индекс: месяц)
    по_маршрутам    - таблица: Рейсов, Часы, Среднее_часов_на_рейс (индекс: маршрут)
    по_подрядчикам  - таблица: Заявок, Часы, Руб_за_час, ... (индекс: подрядчик)
    мин_рейсов      - маршруты с меньшим числом рейсов не показываем: среднее по ним ненадёжно
    """
    os.makedirs('output', exist_ok=True)
    os.makedirs(папка_графиков, exist_ok=True)
    sns.set_theme(style="whitegrid", palette="muted")

    # ============================================================
    # ГРАФИК 1: Часы по месяцам, над столбцами число заявок
    # ============================================================
    fig1, ax1 = plt.subplots(figsize=(10, 5))
    столбцы = ax1.bar(по_месяцам.index, по_месяцам['Часы'], color='#4C72B0', edgecolor='white')

    # Над каждым столбцом подписываем, из скольких заявок он набран
    for столбец, заявок in zip(столбцы, по_месяцам['Заявок']):
        ax1.text(столбец.get_x() + столбец.get_width() / 2, столбец.get_height() + 2,
                 f'{int(заявок)} заяв.', ha='center', va='bottom', fontsize=9, color='#444444')

    ax1.set_title(f'Часы работы техники по месяцам, цех {цех_для_анализа}', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Месяц', fontsize=11)
    ax1.set_ylabel('Часы', fontsize=11)
    ax1.set_ylim(0, по_месяцам['Часы'].max() * 1.12)   # запас сверху под подписи
    plt.xticks(rotation=45, ha='right')
    plt.tight_layout()
    fig1.savefig(f'{папка_графиков}/01_hours_by_month.png', dpi=150, bbox_inches='tight')
    plt.close(fig1)

    # ============================================================
    # ГРАФИК 2: Маршруты по среднему времени рейса
    # ============================================================
    # Оставляем маршруты с достаточным числом рейсов и берём 10 самых долгих
    топ_маршруты = (по_маршрутам[по_маршрутам['Рейсов'] >= мин_рейсов]
                    .sort_values('Среднее_часов_на_рейс', ascending=False)
                    .head(10))
    # Среднее время рейса по всему цеху: суммарные часы / число рейсов
    среднее_по_цеху = по_маршрутам['Часы'].sum() / по_маршрутам['Рейсов'].sum()

    fig2, ax2 = plt.subplots(figsize=(10, 6))
    # [::-1] переворачивает порядок, чтобы самый долгий маршрут оказался сверху
    названия = топ_маршруты.index[::-1]
    значения = топ_маршруты['Среднее_часов_на_рейс'].values[::-1]
    рейсов = топ_маршруты['Рейсов'].values[::-1]
    # Маршруты, где рейс в 1,5 раза дольше среднего, выделяем красным
    цвета = ['#C44E52' if v >= 1.5 * среднее_по_цеху else '#55A868' for v in значения]
    ax2.barh(названия, значения, color=цвета)

    # Вертикальная линия: среднее по цеху
    ax2.axvline(среднее_по_цеху, color='#333333', linestyle='--', linewidth=1)
    ax2.text(среднее_по_цеху, len(названия) - 0.4, f' среднее по цеху: {среднее_по_цеху:.1f} ч',
             va='bottom', fontsize=9, color='#333333')

    # Справа от каждого столбца: значение и число рейсов
    for i, (значение, число) in enumerate(zip(значения, рейсов)):
        ax2.text(значение + 0.1, i, f'{значение:.1f} ч ({int(число)} рейсов)', va='center', fontsize=9)

    ax2.set_title(f'Маршруты по среднему времени рейса (от {мин_рейсов} рейсов), цех {цех_для_анализа}',
                  fontsize=13, fontweight='bold')
    ax2.set_xlabel('Часов на рейс', fontsize=11)
    ax2.set_ylabel('')
    ax2.set_xlim(0, значения.max() * 1.3)
    plt.tight_layout()
    fig2.savefig(f'{папка_графиков}/02_routes_trip_time.png', dpi=150, bbox_inches='tight')
    plt.close(fig2)

    # ============================================================
    # ГРАФИК 3: Стоимость одного часа по подрядчикам
    # ============================================================
    # Подрядчиков уже отсортировали по убыванию Руб_за_час в агрегации
    # Средняя ставка по цеху, если бы все работали по одной цене: затраты / часы
    средняя_ставка = (по_подрядчикам['Стоимость_тыс_руб'].sum() * 1000) / по_подрядчикам['Часы'].sum()

    fig3, ax3 = plt.subplots(figsize=(9, 5))
    ставки = по_подрядчикам['Руб_за_час']
    # Самый дорогой подрядчик красным, остальные синим
    цвета3 = ['#C44E52' if s == ставки.max() else '#4C72B0' for s in ставки]
    столбцы3 = ax3.bar(по_подрядчикам.index, ставки, color=цвета3, edgecolor='white')

    # Подписи внутри столбцов, белым цветом: так они не пересекаются с линией средней ставки
    for столбец, ставка, доля_ч, доля_с in zip(столбцы3, ставки,
                                                по_подрядчикам['Доля_часов_%'],
                                                по_подрядчикам['Доля_стоимости_%']):
        x = столбец.get_x() + столбец.get_width() / 2
        ax3.text(x, ставка * 0.93, f'{ставка:,.0f} руб.'.replace(',', ' '),
                 ha='center', va='top', fontsize=11, fontweight='bold', color='white')
        ax3.text(x, ставка * 0.60, f'часов {доля_ч:.0f}%\nзатрат {доля_с:.0f}%',
                 ha='center', va='top', fontsize=9, color='white')

    # Линия средней ставки подписывается в легенде, а не текстом на графике
    ax3.axhline(средняя_ставка, color='#333333', linestyle='--', linewidth=1.2,
                label=f'средняя по цеху: {средняя_ставка:,.0f} руб.'.replace(',', ' '))
    ax3.legend(loc='upper right', frameon=True)

    ax3.set_title(f'Стоимость одного часа по подрядчикам, цех {цех_для_анализа}', fontsize=14, fontweight='bold')
    ax3.set_xlabel('')
    ax3.set_ylabel('Рублей за час (без НДС)', fontsize=11)
    ax3.set_ylim(0, ставки.max() * 1.15)
    plt.xticks(rotation=15)
    plt.tight_layout()
    fig3.savefig(f'{папка_графиков}/03_contractor_hour_cost.png', dpi=150, bbox_inches='tight')
    plt.close(fig3)

    # ============================================================
    # ГРАФИК 4: Объём работ грузовой техники по типам груза
    # ============================================================
    fig4, ax4 = plt.subplots(figsize=(8, 6))
    
    # Переворачиваем, чтобы самый объемный груз был сверху
    названия_грузов = по_грузам.index[::-1]
    значения_часов = по_грузам['Часы'].values[::-1]
    доли_проценты = по_грузам['Доля_часов_%'].values[::-1]
    
    # Используем пастельную палитру для наглядности категорий
    цвета_грузов = sns.color_palette("pastel", len(названия_грузов))
    
    ax4.barh(названия_грузов, значения_часов, color=цвета_грузов, edgecolor='white')
    
    # Подписи значений и процентов справа от столбцов
    for i, (часы, доля) in enumerate(zip(значения_часов, доли_проценты)):
        ax4.text(часы + (значения_часов.max() * 0.02), i, 
                 f'{часы:.0f} ч ({доля}%)', va='center', fontsize=10, color='#333333')
    
    ax4.set_title(f'Объем работ по типам груза, цех {цех_для_анализа}', fontsize=14, fontweight='bold')
    ax4.set_xlabel('Фактические часы', fontsize=11)
    ax4.set_xlim(0, значения_часов.max() * 1.15) # Запас справа для подписей
    plt.tight_layout()
    fig4.savefig(f'{папка_графиков}/04_cargo_volume.png', dpi=150, bbox_inches='tight')
    plt.close(fig4)

    print("✅ Графики сохранены в папку output/")

