"""
Генератор синтетических данных для проекта «Объединение реестров и отчёта по заявкам».

Создаёт три файла Excel, на которых работает основной скрипт:
  - отчет_по_статусу_заявок.xlsx      (1С:TMS — источник с маршрутами и грузами)
  - Справочник ТС (для реестра).xlsx
  - Реестры 2025 (Все).xlsx           (ручной реестр подрядчиков — только факт работы)

Все данные выдуманные. Запуск: python generate_data.py
Зерно генератора случайных чисел фиксировано, поэтому результат одинаков при каждом запуске.

Структура источников:
  ОТЧЁТ (1С:TMS): Номер, Тип ТС, Дата, Подразделение, Цех, Статус, Тип груза, Адреса
  РЕЕСТР (ручной): Номер/талон, Дата, ТС, Госномер, Подрядчик, Часы, Сумма, Месяц, Код цеха

В данные заложены:
  1. «Грязные» номера заявок и госномера (то, что чистит основной скрипт).
  2. Часть строк реестра, которых нет в отчёте: для одних запасное объединение
     (по дате, транспорту и цеху) находит пару, для других нет.
  3. Закономерности, которые должны выявить агрегации:
       - подрядчик «В» берёт больше за час работы, чем остальные;
       - два маршрута занимают заметно больше часов, чем остальные;
       - летом заявок больше, чем зимой;
       - разные типы грузов имеют разную долю в объёме.
"""
import numpy as np
import pandas as pd
import os

# ---------------------------------------------------------------- Пути (надёжные, работают отовсюду)
ПАПКА_СКРИПТА = os.path.dirname(os.path.abspath(__file__))
ПАПКА_DATA = os.path.join(ПАПКА_СКРИПТА, 'data')

rng = np.random.default_rng(42)  # фиксированное зерно: данные одинаковые при каждом запуске

# ---------------------------------------------------------------- Параметры
N_ОТЧЕТ = 500                 # строк в отчёте по заявкам
N_РЕЕСТР = 800                # строк в реестре
ДОЛЯ_БЕЗ_НОМЕРА = 0.08        # доля строк реестра с номером заявки, которого нет в отчёте
ДОЛЯ_НАЙДЕННЫХ_ЗАПАСНЫМ = 0.65  # из них у такой доли дата, транспорт и цех совпадают с реальной заявкой

# ---------------------------------------------------------------- Справочники
справочник_тс = pd.DataFrame({
    'Наименование транспортного средства': [
        'Самосвал 20 т', 'Самосвал 10 т', 'Бортовой 10 т', 'Бортовой 5 т',
        'Тягач с полуприцепом', 'Автобус 40 мест', 'Автокран 25 т', 'Погрузчик фронтальный'],
    'ТС': ['САМ20', 'САМ10', 'БОРТ10', 'БОРТ5', 'ТЯГАЧ', 'АВТ40', 'КРАН25', 'ПОГР'],
})
типы = справочник_тс['Наименование транспортного средства'].tolist()

цеха = {57: 'Цех подготовки', 12: 'Цех 1', 23: 'Цех 2', 34: 'Цех 3', 45: 'Цех 4'}
коды_цехов = list(цеха)
доли_цехов = [0.35, 0.15, 0.15, 0.20, 0.15]   # в цехе 57 больше заявок: именно его анализирует скрипт

месяцы = ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь',
          'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь']
# Сезонность: к лету заявок больше (веса по месяцам, сумма = 1)
веса_месяцев = np.array([0.05, 0.05, 0.07, 0.08, 0.09, 0.12, 0.14, 0.13, 0.09, 0.08, 0.05, 0.05])
веса_месяцев = веса_месяцев / веса_месяцев.sum()

места = ['Склад 1', 'Склад 2', 'Площадка А', 'Площадка Б', 'Участок 3', 'Карьер']
# Два маршрута с аномально большим временем (в 1,8 раза дольше обычного)
дальние_маршруты = {('Карьер', 'Склад 1'), ('Участок 3', 'Площадка А')}

подрядчики = ['ООО Подрядчик А', 'ООО Подрядчик Б', 'ООО Подрядчик В', 'ООО Подрядчик Г']
доли_подрядчиков = [0.25, 0.25, 0.20, 0.30]
# Ставка за час, руб. Подрядчик «В» заметно дороже остальных
ставка_за_час = {'ООО Подрядчик А': 1900, 'ООО Подрядчик Б': 2000,
                 'ООО Подрядчик В': 2800, 'ООО Подрядчик Г': 1950}

буквы_номеров = list('АВЕКМНОРСТУХ')

# Типы грузов с долями (песок — основной объём)
типы_грузов = ['Песок', 'Щебень', 'Грунт', 'Отходы', 'Скальная порода']
доли_грузов = [0.45, 0.25, 0.15, 0.10, 0.05]

# ---------------------------------------------------------------- Отчёт по статусу заявок (1С:TMS)
числа = rng.choice(np.arange(10000, 99999), N_ОТЧЕТ, replace=False)  # уникальные номера заявок

# Месяц выбираем с весами (сезонность), день внутри месяца случайный
месяц_заявки = rng.choice(np.arange(1, 13), N_ОТЧЕТ, p=веса_месяцев)
даты = pd.to_datetime([
    pd.Timestamp(2025, int(m), 1) + pd.Timedelta(days=int(rng.integers(0, 28)))
    for m in месяц_заявки
])

коды = rng.choice(коды_цехов, N_ОТЧЕТ, p=доли_цехов)
типы_отчета = rng.choice(типы, N_ОТЧЕТ)
грузы = rng.choice(типы_грузов, N_ОТЧЕТ, p=доли_грузов)

# Адреса маршрутов генерируем в отчёте
адреса_отправления = rng.choice(места, N_ОТЧЕТ)
адреса_получения = []
for отпр in адреса_отправления:
    # Получение — любое место, кроме отправления
    варианты = [м for м in места if м != отпр]
    адреса_получения.append(rng.choice(варианты))
адреса_получения = np.array(адреса_получения)


def номер_в_отчете(n):
    """Номер заявки с «мусором»: буква спереди, нули, иногда пробел внутри."""
    приставка = str(rng.choice(['А', 'a', 'А', '']))   # латиница и кириллица
    нули = str(rng.choice(['', '0', '00']))
    s = str(n)
    if rng.random() < 0.05:
        s = s[:2] + ' ' + s[2:]
    return приставка + нули + s


отчет = pd.DataFrame({
    'Номер': [номер_в_отчете(n) for n in числа],
    'Тип ТС': типы_отчета,
    'Дата заявки': даты.strftime('%d.%m.%Y'),
    'Подразделение': [f'Подразделение {к}' for к in коды],
    'Наименование цеха': [цеха[к] for к in коды],
    'Статус заявки': rng.choice(['Выполнена', 'В работе', ' '], N_ОТЧЕТ, p=[0.8, 0.15, 0.05]),
    'Тип груза': грузы,                          
    'Адрес отправления': адреса_отправления,     
    'Адрес получения': адреса_получения,         
})
отчет[''] = np.nan                                                    # пустой столбец
отчет = pd.concat([отчет.iloc[:10], pd.DataFrame([{}]), отчет.iloc[10:]], ignore_index=True)  # пустая строка

# Комбинации «дата + транспорт + цех», которые реально есть в отчёте
# (нужны, чтобы создать строки, которые запасное объединение НЕ найдёт)
есть_в_отчете = set(zip(даты, типы_отчета, коды))


# ---------------------------------------------------------------- Реестр (ручной, только факт работы)
def номер_в_реестре(n, дата):
    """Номер заявки/талона в разных «грязных» форматах."""
    нули = str(rng.choice(['', '0', '00']))
    вариант = rng.choice(['слэш', 'без_слэша', 'от', 'скобка', 'перенос'],
                         p=[0.60, 0.15, 0.08, 0.07, 0.10])
    if вариант == 'слэш':
        return f'{rng.choice(["ЦП", "Ц1", "АБ"])}/{нули}{n}'
    if вариант == 'без_слэша':
        return f'{нули}{n}'
    if вариант == 'от':
        return f'{n} от {дата.strftime("%d.%m")}'
    if вариант == 'скобка':
        return f'{n} (подр.)'
    return f'{n}\nдоп'


def госномер():
    """Госномер в разных написаниях."""
    б1 = str(rng.choice(буквы_номеров))
    цифры = int(rng.integers(100, 999))
    б2 = ''.join(rng.choice(буквы_номеров, 2))
    регион = str(rng.choice(['48', '48', '48', '31', '36']))
    вид = rng.choice(['чистый', 'rus', 'слэш', 'пробелы'], p=[0.7, 0.1, 0.1, 0.1])
    if вид == 'чистый':
        return f'{б1}{цифры}{б2}{регион}'
    if вид == 'rus':
        return f'{б1}{цифры}{б2}{регион} RUS'
    if вид == 'слэш':
        return f'{б1}{цифры}{б2}/{регион}'
    return f'{б1} {цифры} {б2} {регион}'


def дата_без_пары(дата, тип_тс, код):
    """Сдвигаем дату на несколько дней, пока комбинация не окажется отсутствующей в отчёте."""
    for _ in range(50):
        новая = дата + pd.Timedelta(days=int(rng.integers(1, 6)))
        if (новая, тип_тс, код) not in есть_в_отчете:
            return новая
    return дата + pd.Timedelta(days=30)


источник = rng.integers(0, N_ОТЧЕТ, N_РЕЕСТР)            # какую заявку из отчёта «берёт» строка реестра
без_номера = rng.random(N_РЕЕСТР) < ДОЛЯ_БЕЗ_НОМЕРА     # у этих строк номера заявки нет в отчёте
найдется_запасным = rng.random(N_РЕЕСТР) < ДОЛЯ_НАЙДЕННЫХ_ЗАПАСНЫМ

строки = []
for i in range(N_РЕЕСТР):
    j = источник[i]
    дата, тип_тс, код = даты[j], типы_отчета[j], int(коды[j])

    if без_номера[i]:
        n = int(rng.integers(900000, 999999))                    # номера нет в отчёте
        if not найдется_запасным[i]:
            дата = дата_без_пары(дата, тип_тс, код)              # и запасной ключ ничего не найдёт
    else:
        n = int(числа[j])

    подрядчик = rng.choice(подрядчики, p=доли_подрядчиков)

    часы = float(rng.uniform(2, 10))
    часы = round(часы, 1)
    стоимость = round(часы * ставка_за_час[подрядчик] * float(rng.normal(1, 0.05)), 2)

    строки.append({
        'Номер заявки/талона': номер_в_реестре(n, дата),
        'Дата начала по заявке (для спецтехники)': дата,
        'Наименование транспортного средства': тип_тс,
        'Регистрационный номер автомобиля': госномер(),
        'Наименование КА': подрядчик,
        'Фактическое время для оплаты согласно СКУД': часы,
        'Сумма итог руб. без НДС': стоимость,
        'Месяц': месяцы[дата.month - 1],
        'Код цеха ': код,                     # нужен для fallback-мерджа в main.py
    })

реестр = pd.DataFrame(строки)
реестр[''] = np.nan                                                    # пустой столбец
реестр = pd.concat([реестр.iloc[:5], pd.DataFrame([{}]), реестр.iloc[5:]], ignore_index=True)  # пустая строка

# ---------------------------------------------------------------- Сохранение
# Гарантируем создание папки data рядом со скриптом
os.makedirs(ПАПКА_DATA, exist_ok=True)

путь_отчета = os.path.join(ПАПКА_DATA, 'отчет_по_статусу_заявок.xlsx')
путь_справочника = os.path.join(ПАПКА_DATA, 'Справочник ТС (для реестра).xlsx')
путь_реестра = os.path.join(ПАПКА_DATA, 'Реестры 2025 (Все).xlsx')

with pd.ExcelWriter(путь_отчета, engine='openpyxl') as w:
    отчет.to_excel(w, index=False, startrow=3, sheet_name='Отчет')   # три верхние строки под «шапку»
    w.sheets['Отчет']['A1'] = 'Отчёт по статусу заявок'
    w.sheets['Отчет']['A2'] = 'Период: 2025 год'

справочник_тс.to_excel(путь_справочника, index=False)
реестр.to_excel(путь_реестра, index=False)

print(f'✅ Готово: строк в отчёте {N_ОТЧЕТ}, в реестре {N_РЕЕСТР}')
print(f'📁 Файлы сохранены в: {ПАПКА_DATA}')